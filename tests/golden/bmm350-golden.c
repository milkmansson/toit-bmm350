// Generates golden test vectors for the Toit BMM350 driver.
//
// This program includes Bosch Sensortec's own BMM350 sensor API source and
// feeds it synthetic OTP words and raw register bytes. The numbers it prints
// are what Bosch's code computes, so the Toit driver can be compared against
// them without any hardware.
//
// Build and run (needs the Bosch API files in ../../.reference):
//   gcc -std=gnu99 -I../../.reference -o bmm350-golden bmm350-golden.c -lm
//   ./bmm350-golden > ../golden-vectors.toit
//
// The Bosch source is not part of the published package. It is licensed by
// Bosch Sensortec and is kept locally in .reference/ only.

#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <math.h>

#include "bmm350.c"

// The fake bus. Only the data registers are served; everything else reads 0.
// Like the real chip, each read returns two dummy bytes first.
static uint8_t fake_data[12];

static BMM350_INTF_RET_TYPE fake_read(uint8_t reg, uint8_t *buf, uint32_t len,
                                       void *intf) {
  (void) intf;
  memset(buf, 0xA5, len);
  if (reg == BMM350_REG_MAG_X_XLSB && len >= 14) memcpy(buf + 2, fake_data, 12);
  return 0;
}

static BMM350_INTF_RET_TYPE fake_write(uint8_t reg, const uint8_t *buf,
                                        uint32_t len, void *intf) {
  (void) reg; (void) buf; (void) len; (void) intf;
  return 0;
}

static void fake_delay(uint32_t us, void *intf) { (void) us; (void) intf; }

static uint32_t lcg_state = 0x350;
static uint32_t lcg(void) {
  lcg_state = lcg_state * 1664525u + 1013904223u;
  return lcg_state >> 8;
}

static void put24(uint8_t *out, int32_t v) {
  out[0] = v & 0xFF;
  out[1] = (v >> 8) & 0xFF;
  out[2] = (v >> 16) & 0xFF;
}

static void print_case(const char *name, const uint16_t *otp,
                       const int32_t *raw /* x y z t, signed */) {
  struct bmm350_dev dev;
  memset(&dev, 0, sizeof(dev));
  dev.read = fake_read;
  dev.write = fake_write;
  dev.delay_us = fake_delay;
  dev.axis_en = BMM350_EN_XYZ_MSK;
  memcpy(dev.otp_data, otp, sizeof(dev.otp_data));
  update_mag_off_sens(&dev);

  put24(fake_data + 0, raw[0]);
  put24(fake_data + 3, raw[1]);
  put24(fake_data + 6, raw[2]);
  put24(fake_data + 9, raw[3]);

  float plain[4];
  read_out_raw_data(plain, &dev);

  struct bmm350_mag_temp_data comp;
  bmm350_get_compensated_mag_xyz_temp_data(&comp, &dev);

  printf("  {\n");
  printf("    \"name\": \"%s\",\n", name);
  printf("    \"otp\": [");
  for (int i = 0; i < 32; i++) printf("%s0x%04x", i ? ", " : "", otp[i]);
  printf("],\n");
  printf("    // x, y, z, temperature as 24-bit register bytes, then 3 sensortime bytes.\n");
  printf("    \"raw\": #[");
  for (int i = 0; i < 12; i++) printf("%s0x%02x", i ? ", " : "", fake_data[i]);
  printf(", 0x00, 0x00, 0x00],\n");
  printf("    \"mag\": [%.9g, %.9g, %.9g],\n", plain[0], plain[1], plain[2]);
  printf("    \"temp\": %.9g,\n", plain[3]);
  printf("    \"mag-comp\": [%.9g, %.9g, %.9g],\n", comp.x, comp.y, comp.z);
  printf("    \"temp-comp\": %.9g,\n", comp.temperature);
  printf("    \"offsets\": [%.9g, %.9g, %.9g],\n",
         dev.mag_comp.dut_offset_coef.offset_x,
         dev.mag_comp.dut_offset_coef.offset_y,
         dev.mag_comp.dut_offset_coef.offset_z);
  printf("    \"t0\": %.9g,\n", dev.mag_comp.dut_t0);
  printf("  },\n");
}

int main(void) {
  printf("// Copyright (C) 2026 Toit Contributors\n");
  printf("// Use of this source code is governed by a Zero-Clause BSD license that can\n");
  printf("// be found in the EXAMPLES_LICENSE file.\n\n");
  printf("// Generated by tests/golden/bmm350-golden.c from Bosch Sensortec's BMM350\n");
  printf("// sensor API. Do not edit by hand.\n\n");
  printf("GOLDEN-CASES ::= [\n");

  // Case 1: hand-picked words with small trims, close to what a real part holds.
  uint16_t otp1[32] = {0};
  otp1[0x0D] = 0x0203;  // Temperature offset (low byte) and sensitivity (high byte).
  otp1[0x0E] = 0x0012;
  otp1[0x0F] = 0x000B;
  otp1[0x10] = 0xF105;
  otp1[0x11] = 0x03FA;
  otp1[0x12] = 0x0405;
  otp1[0x13] = 0xFD02;
  otp1[0x14] = 0x0306;
  otp1[0x15] = 0x04FC;
  otp1[0x16] = 0xFE03;
  otp1[0x18] = 0x0040;
  int32_t raw1[4] = {2800, -1500, 6200, 51452};
  print_case("small trims, typical field", otp1, raw1);

  // Cases 2 to 7: pseudo-random trim words and several fields, including
  // negative values on every axis and a negative temperature reading.
  int32_t fields[6][4] = {
    {  70000, -120000,   30000, 52000},
    { -90000,   40000, -200000, 49000},
    {      0,       0,       0, 51452},
    { 280000,  280000,  280000, 60000},
    {-280000, -280000, -280000, 40000},
    {   1234,   -4321,     999, -30000},
  };
  for (int c = 0; c < 6; c++) {
    uint16_t otp[32];
    for (int i = 0; i < 32; i++) otp[i] = (uint16_t) lcg();
    char name[64];
    snprintf(name, sizeof(name), "pseudo-random trims %d", c + 1);
    print_case(name, otp, fields[c]);
  }

  printf("]\n");
  return 0;
}
